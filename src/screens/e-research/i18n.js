const normalizeLanguage = (language) =>
  String(language || "").toLowerCase().startsWith("en") ? "en" : "th";

const interpolate = (template, params = {}) =>
  String(template).replace(/\{\{(\w+)\}\}/g, (_, key) =>
    params[key] === undefined || params[key] === null ? "" : String(params[key]),
  );

export const translateEResearch = (language, key, params = {}) => {
  const lang = normalizeLanguage(language);
  const value = dictionaries[lang]?.[key] ?? dictionaries.th[key] ?? key;
  return interpolate(value, params);
};

export const useEResearchText = () => {
  const { i18n } = useTranslation();
  const language = normalizeLanguage(i18n.language);
  const te = useMemo(
    () => (key, params) => translateEResearch(language, key, params),
    [language],
  );

  return { te, eResearchLanguage: language };
};

export const withPlaceholder = (options, placeholder) =>
  options.map((option, index) =>
    index === 0 || option.id === "" ? { ...option, label: placeholder } : option,
  );
